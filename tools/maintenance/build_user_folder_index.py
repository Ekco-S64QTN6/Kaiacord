#!/usr/bin/env python3
"""
tools/maintenance/build_user_folder_index.py

Write a README.md into each user folder: what is here, and what it covers.

Opening `Ekco_177011971818782721/` used to mean 178 undifferentiated daily
files and one generated profile, which answers none of the questions a person
actually has — how long have they talked, about what, where do I look for a
given month, what has this person shared.

Everything here is derived from the transcripts themselves. No model is
involved, so it is cheap, regenerable, and cannot invent anything.

    python tools/maintenance/build_user_folder_index.py --apply
"""
import argparse
import re
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))

USER_LOGS = ROOT / "knowledge_base" / "user_logs"

TURN = re.compile(r"^\[(\d{4}-\d\d-\d\d) \d\d:\d\d:\d\d\] ([^:\n]+): (.*?)(?=^\[\d{4}-|\Z)",
                  re.M | re.S)
SHARED = re.compile(r"^\[shared link: (.+?)\]$", re.M)

